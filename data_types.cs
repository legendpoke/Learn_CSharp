using System;
using System.Collections.Generic;
using System.Text;

namespace C__Course
{
    class DataTypes {
        static void Data_Types(string[] args) {
            int a = 10;
            Console.WriteLine(a);
            long b = 100000L;
            Console.WriteLine(b);
            float c = 1.0f;
            Console.WriteLine(c);
            double d = 3.14156;
            Console.WriteLine(d);
            decimal e = 500000.50m;
            Console.WriteLine(e);
            bool isActive = true;
            Console.WriteLine(isActive);
            char f = 'a';
            Console.WriteLine(f);
            byte g = 255;
            Console.WriteLine(g);
            string h = "hello";
            Console.WriteLine(h);
            object i = 45;
            Console.WriteLine(i);
            int [] nums = { 1, 2, 3, 4, 5, 6 };
            Console.WriteLine(nums);
            var msg = "hii";
            Console.WriteLine(msg);
            var age = 20;
            Console.WriteLine(age);
            var price = 19.99;
            Console.WriteLine(price);
        }
    }
}
